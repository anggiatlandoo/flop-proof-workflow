#!/usr/bin/env python3
"""Generate a structured proof-of-contribution record for Flop Labs.

Creates a JSON record and a Markdown rendering of a contribution to the
Technocore / Flop Labs ecosystem, tied to the contributor's public DID.

The record contains a UTC timestamp and a SHA-256 content hash computed
over the record fields, so anyone can later check with
verify_contribution.py that the record has not been altered.

Standard library only. No network access. No private key is ever needed:
only the public DID (did:key:z...) is recorded.

Usage:
    python3 generate_contribution_record.py \
        --title "What is a Technocore DID?" \
        --description "A beginner-friendly X thread explaining DIDs, the Technocore registry, and the signed lobby check-in." \
        --url "https://x.com/yourhandle/status/1234567890" \
        --type "kol-thread" \
        --did "did:key:z6MkmZAR1ePxsJgaES7HtyvKtamQyTybu9GBzuqFK6GwVyZi" \
        --author "yourhandle" \
        --output contribution_record
"""

import argparse
import hashlib
import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

VALID_TYPES = {
    "kol-thread": "KOL / Educator",
    "open-source": "Open-Source Builder",
    "bug-report": "Bug Reporter",
    "community-help": "Community Helper",
    "content": "Content Creator",
}

# Aliases for the names contributors reach for most often. They are
# normalised to the canonical slug before the record is written, so the
# stored record always uses a slug from references/contribution-types.md.
TYPE_ALIASES = {
    "thread": "kol-thread",
    "tutorial": "content",
}

# A Technocore DID is did:key:z followed by a base58 Ed25519 public key.
# Base58 excludes 0, O, I and l.
DID_PATTERN = re.compile(r"^did:key:z[1-9A-HJ-NP-Za-km-z]+$")

URL_PATTERN = re.compile(r"^https?://\S+$")


def canonical_payload(record):
    """Return the canonical JSON bytes the content hash is computed over."""
    payload = {
        "title": record["title"],
        "description": record["description"],
        "url": record["url"],
        "type": record["type"],
        "author": record["author"],
        "did": record["did"],
        "timestamp": record["timestamp"],
    }
    return json.dumps(payload, sort_keys=True, separators=(",", ":"),
                      ensure_ascii=False).encode("utf-8")


def compute_hash(record):
    return hashlib.sha256(canonical_payload(record)).hexdigest()


def render_markdown(record):
    lines = [
        "# Contribution Record",
        "",
        f"- **Title:** {record['title']}",
        f"- **Type:** {record['type']} ({VALID_TYPES[record['type']]})",
        f"- **Author:** {record['author']}",
        f"- **URL:** {record['url']}",
        f"- **DID:** {record['did']}",
        f"- **Timestamp:** {record['timestamp']}",
        f"- **Content Hash (SHA-256):** {record['content_hash']}",
        "",
        "## Description",
        "",
        record["description"],
        "",
        "Generated by the Flop Contribution Proof Generator skill. "
        "Verify with: python3 scripts/verify_contribution.py "
        f"{Path(record['_json_file']).name}",
        "",
    ]
    return "\n".join(lines)


def parse_args(argv):
    parser = argparse.ArgumentParser(
        description="Generate a Flop Labs proof-of-contribution record.")
    parser.add_argument("--title", required=True,
                        help="Title of the contribution.")
    parser.add_argument("--description", required=True,
                        help="Short description of the contribution.")
    parser.add_argument("--url", required=True,
                        help="Public URL of the contribution.")
    parser.add_argument("--type", required=True,
                        choices=sorted(set(VALID_TYPES) | set(TYPE_ALIASES)),
                        help="Contribution type: "
                             + ", ".join(sorted(VALID_TYPES))
                             + " (aliases: thread -> kol-thread, "
                             "tutorial -> content)")
    parser.add_argument("--did", required=True,
                        help="Your public DID, e.g. did:key:z6Mk...")
    parser.add_argument("--author", default="",
                        help="Your public handle or name (optional).")
    parser.add_argument("--output", default="contribution_record",
                        help="Base name for the output files "
                             "(default: contribution_record).")
    return parser.parse_args(argv)


def main(argv=None):
    args = parse_args(argv)

    # Normalise an alias to its canonical slug before anything is written.
    args.type = TYPE_ALIASES.get(args.type, args.type)

    if not DID_PATTERN.match(args.did):
        print("error: --did must be a valid Technocore DID "
              "(did:key:z... Ed25519 public identity).", file=sys.stderr)
        return 2
    if not URL_PATTERN.match(args.url):
        print("error: --url must be a public http(s) URL.", file=sys.stderr)
        return 2

    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

    record = {
        "title": args.title.strip(),
        "description": args.description.strip(),
        "url": args.url.strip(),
        "type": args.type,
        "author": args.author.strip(),
        "did": args.did.strip(),
        "timestamp": timestamp,
    }
    if not record["title"] or not record["description"]:
        print("error: --title and --description must not be empty.",
              file=sys.stderr)
        return 2

    record["content_hash"] = compute_hash(record)

    json_path = Path(args.output + ".json")
    md_path = Path(args.output + ".md")
    record["_json_file"] = str(json_path)
    markdown = render_markdown(record)

    public_record = {key: value for key, value in record.items()
                     if not key.startswith("_")}
    json_path.write_text(json.dumps(public_record, indent=2,
                                   ensure_ascii=False) + "\n",
                         encoding="utf-8")
    md_path.write_text(markdown, encoding="utf-8")

    print(f"Contribution record created for DID {record['did']}")
    print(f"  JSON:     {json_path}")
    print(f"  Markdown: {md_path}")
    print(f"  Timestamp: {record['timestamp']}")
    print(f"  Content Hash (SHA-256): {record['content_hash']}")
    print("Verify it with: "
          f"python3 scripts/verify_contribution.py {json_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
